#!/usr/bin/env python3
# Turn a .nnue file into cf_net.h so the net is compiled into the engine (single-binary distribution).
# usage: python3 net2h.py claudefish.nnue > cf_net.h
import sys
d = open(sys.argv[1], 'rb').read()
print("// generated by net2h.py - embedded ClaudeFish NNUE net (%d bytes)" % len(d))
print("static const unsigned char CF_NET[%d] = {" % len(d))
for i in range(0, len(d), 32):
    print(",".join(str(b) for b in d[i:i+32]) + ("," if i + 32 < len(d) else ""))
print("};")
